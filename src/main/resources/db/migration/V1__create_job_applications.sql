-- Tabella delle candidature
CREATE TABLE job_applications (
                                  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                  company           VARCHAR(255)                NOT NULL,
                                  position          VARCHAR(255)                NOT NULL,
                                  job_url           VARCHAR(2048),
                                  description       TEXT,
                                  location          VARCHAR(255),
                                  work_mode         VARCHAR(30),
                                  status            VARCHAR(30)                 NOT NULL DEFAULT 'TO_APPLY',
                                  application_date  DATE,
                                  notes             TEXT,
                                  created_at        TIMESTAMP(6) WITH TIME ZONE NOT NULL,
                                  updated_at        TIMESTAMP(6) WITH TIME ZONE NOT NULL,

                                  CONSTRAINT chk_job_applications_work_mode
                                      CHECK (work_mode IN ('ONSITE', 'HYBRID', 'REMOTE')),

                                  CONSTRAINT chk_job_applications_status
                                      CHECK (status IN ('TO_APPLY', 'APPLIED', 'INTERVIEW', 'REJECTED', 'OFFER', 'WITHDRAWN'))
);

-- Indice per velocizzare i filtri per stato (es. "mostrami tutti i colloqui")
CREATE INDEX idx_job_applications_status ON job_applications (status);